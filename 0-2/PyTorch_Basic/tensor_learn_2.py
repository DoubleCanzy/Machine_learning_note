import torch

x = torch.tensor([
    [1, 2],
    [3, 4],
    [5, 6]
])

#1.取出指定的元素
print(x[0])
print(x[0, 1])
print(x[2, 0])
#PyTorch 的索引和 Python 列表一样，从 0 开始计数。
#- x[0]：取第 1 行，结果是一维 Tensor。
#- x[0, 1]：取第 1 行、第 2 列，结果是一个标量 Tensor。
#- x[2, 0]：取第 3 行、第 1 列。

#切片
print(x[:, 0])
print(x[:, 1])
print(x[0:2, :])

#写法	含义
#x[:, 0]	所有行，第 1 列
#x[:, 1]	所有行，第 2 列
#x[0:2, :]	第 1、2 行，所有列
#其中，冒号 : 表示选取该维度上的全部元素；0:2 表示从索引 0 开始，取到索引 2 之前，不包含索引 2。